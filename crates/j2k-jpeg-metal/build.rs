//! Renders the JPEG IDCT constants of `j2k_codec_math::jpeg::idct` into the
//! Metal fragment `$OUT_DIR/jpeg_idct_constants.metal`, which leads the
//! shader source, so the shaders carry no hand-copied value.

use std::env;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use j2k_codec_math::jpeg::idct;

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=build.rs");
    let constants: [(&str, i64); 32] = [
        ("CONST_BITS", i64::try_from(idct::CONST_BITS)?),
        ("PASS1_BITS", i64::try_from(idct::PASS1_BITS)?),
        ("PASS1_SHIFT", idct::PASS1_SHIFT.into()),
        ("PASS1_ROUNDING", idct::PASS1_ROUNDING.into()),
        ("PASS2_SHIFT", idct::PASS2_SHIFT.into()),
        ("PASS2_ROUNDING", idct::PASS2_ROUNDING.into()),
        ("DC_SHIFT", idct::DC_SHIFT.into()),
        ("DC_ROUNDING", idct::DC_ROUNDING.into()),
        ("PASS1_SHIFT_12", idct::PASS1_SHIFT_12.into()),
        ("PASS2_SHIFT_12", idct::PASS2_SHIFT_12.into()),
        ("FIX_0_298631336", idct::FIX_0_298631336.into()),
        ("FIX_0_390180644", idct::FIX_0_390180644.into()),
        ("FIX_0_541196100", idct::FIX_0_541196100.into()),
        ("FIX_0_765366865", idct::FIX_0_765366865.into()),
        ("FIX_0_899976223", idct::FIX_0_899976223.into()),
        ("FIX_1_175875602", idct::FIX_1_175875602.into()),
        ("FIX_1_501321110", idct::FIX_1_501321110.into()),
        ("FIX_1_847759065", idct::FIX_1_847759065.into()),
        ("FIX_1_961570560", idct::FIX_1_961570560.into()),
        ("FIX_2_053119869", idct::FIX_2_053119869.into()),
        ("FIX_2_562915447", idct::FIX_2_562915447.into()),
        ("FIX_3_072711026", idct::FIX_3_072711026.into()),
        ("FIX_0_211164243", idct::FIX_0_211164243.into()),
        ("FIX_0_509795579", idct::FIX_0_509795579.into()),
        ("FIX_0_601344887", idct::FIX_0_601344887.into()),
        ("FIX_0_720959822", idct::FIX_0_720959822.into()),
        ("FIX_0_850430095", idct::FIX_0_850430095.into()),
        ("FIX_1_061594337", idct::FIX_1_061594337.into()),
        ("FIX_1_272758580", idct::FIX_1_272758580.into()),
        ("FIX_1_451774981", idct::FIX_1_451774981.into()),
        ("FIX_2_172734803", idct::FIX_2_172734803.into()),
        ("FIX_3_624509785", idct::FIX_3_624509785.into()),
    ];
    let mut source = String::from(
        "// Generated by crates/j2k-jpeg-metal/build.rs from j2k_codec_math::jpeg::idct.\n",
    );
    for (name, value) in constants {
        writeln!(
            source,
            "constant int CODEC_MATH_JPEG_IDCT_{name} = {value};"
        )?;
    }
    let out_dir = env::var_os("OUT_DIR").ok_or("Cargo did not provide OUT_DIR")?;
    fs::write(
        PathBuf::from(out_dir).join("jpeg_idct_constants.metal"),
        source,
    )?;
    Ok(())
}
