//! Renders the JPEG constants of `j2k_codec_math::jpeg` into the Metal
//! fragment `$OUT_DIR/jpeg_codec_math.metal`, which leads the shader source,
//! so the shaders carry no hand-copied value: the IDCT constants of
//! `jpeg::idct`, the forward DCT basis of `jpeg::fdct` and the colour
//! conversion constants of `jpeg::ycbcr`.

use std::env;
use std::error::Error;
use std::fmt::{Display, Write as _};
use std::fs;
use std::path::PathBuf;

use j2k_codec_math::jpeg::{fdct, idct, ycbcr};

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=build.rs");
    let mut source =
        String::from("// Generated by crates/j2k-jpeg-metal/build.rs from j2k_codec_math::jpeg.\n");
    render_idct(&mut source)?;
    render_fdct(&mut source)?;
    render_ycbcr(&mut source)?;
    let out_dir = env::var_os("OUT_DIR").ok_or("Cargo did not provide OUT_DIR")?;
    fs::write(PathBuf::from(out_dir).join("jpeg_codec_math.metal"), source)?;
    Ok(())
}

