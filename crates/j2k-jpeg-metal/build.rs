fn render_fdct(source: &mut String) -> Result<(), Box<dyn Error>> {
    writeln!(
        source,
        "constant uint CODEC_MATH_JPEG_FDCT_FRACTION_BITS = {};",
        fdct::FRACTION_BITS
    )?;
    render_array(
        source,
        "short",
        "CODEC_MATH_JPEG_FDCT_BASIS_HIGH",
        &fdct::BASIS_HIGH,
    )?;
    render_array(
        source,
        "ushort",
        "CODEC_MATH_JPEG_FDCT_BASIS_LOW",
        &fdct::BASIS_LOW,
    )
}

fn render_ycbcr(source: &mut String) -> Result<(), Box<dyn Error>> {
    let constants: [(&str, i32); 10] = [
        ("FRACTION_BITS", ycbcr::FRACTION_BITS),
        ("ROUND", ycbcr::ROUND),
        ("FIX_0_29900", ycbcr::FIX_0_29900),
        ("FIX_0_58700", ycbcr::FIX_0_58700),
        ("FIX_0_11400", ycbcr::FIX_0_11400),
        ("FIX_0_16874", ycbcr::FIX_0_16874),
        ("FIX_0_33126", ycbcr::FIX_0_33126),
        ("FIX_0_50000", ycbcr::FIX_0_50000),
        ("FIX_0_41869", ycbcr::FIX_0_41869),
        ("FIX_0_08131", ycbcr::FIX_0_08131),
    ];
    for (name, value) in constants {
        writeln!(
            source,
            "constant int CODEC_MATH_JPEG_YCBCR_{name} = {value};"
        )?;
    }
    Ok(())
}

fn render_array<T: Display>(
    source: &mut String,
    element: &str,
    name: &str,
    values: &[T],
) -> Result<(), Box<dyn Error>> {
    writeln!(source, "constant {element} {name}[{}] = {{", values.len())?;
    for row in values.chunks(16) {
        source.push_str("   ");
        for value in row {
            write!(source, " {value},")?;
        }
        source.push('\n');
    }
    source.push_str("};\n");
    Ok(())
}
